# Directory where you want to copy the images
destination_dir = "clean_images/"

# Make sure the destination directory exists
os.makedirs(destination_dir, exist_ok=True)

# Copy each file
for filepath in clean_im_list:
    if os.path.isfile(filepath):  # check if file actually exists
        # Get just the filename (strip the directories)
        filename = os.path.basename(filepath)
        # Construct the full destination path
        dest_path = os.path.join(destination_dir, filename)
        # Copy the file
        shutil.copy2(filepath, dest_path)  # copy2 preserves metadata
        print(f"Copied {filename} → {dest_path}")
    else:
        print(f"File not found: {filepath}")
